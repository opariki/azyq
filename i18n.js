let current = "ru";
try { const l = localStorage.getItem("azyq_lang"); if (l && translations[l]) current = l; } catch (e) {}

export const getLang = () => current;
export function setLang(l) {
  if (!translations[l]) return;
  current = l;
  try { localStorage.setItem("azyq_lang", l); } catch (e) {}
}
/** Translate a key; {name} placeholders are filled from vars. */
export function t(key, vars = {}) {
  const s = translations[current][key] || translations.ru[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : ""));
}
